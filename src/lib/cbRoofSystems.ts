/**
 * Roof system → assembly.
 *
 * The takeoff sheet field cb_takeoffs.data.sheet.roof_system.roof_type is the
 * SELECTOR for the estimate. Every system has its own assembly: its own tear
 * off, its own covering, its own underlayment and its own accessories.
 *
 * There is deliberately NO fallback. If a system has no assembly the estimate
 * must fail loudly rather than quote a shingle price on a tile roof.
 */

export type CbQtyBasis =
  | "squares" /* true roof area, no waste */
  | "squares_waste" /* area + waste */
  | "tearoff" /* true area × layers */
  | "eave_valley"
  | "eave_rake"
  | "ridge_hip"
  | "ridge"
  | "eave"
  | "valley"
  | "perimeter";

export interface CbAssemblyLine {
  key: string;
  /** Every word must appear in the catalog item name. */
  must: string[];
  prefer?: string[];
  avoid?: string[];
  unit: string;
  label: string;
  basis: CbQtyBasis;
  /** LF quantity that becomes SF when the catalog item is sold by SF. */
  lfToSf?: boolean;
  /** Marks the line as the system's underlayment (never defaulted globally). */
  role?: "tearoff" | "covering" | "underlayment" | "accessory";
}

export interface CbAssembly {
  key: string;
  label: string;
  /** Lower-cased fragments of the takeoff value that select this assembly. */
  aliases: string[];
  lines: CbAssemblyLine[];
}

const tearoff = (must: string[], label: string, prefer?: string[]): CbAssemblyLine => ({
  key: "tearoff",
  must,
  prefer,
  avoid: ["ridge", "starter"],
  unit: "SQ",
  label,
  basis: "tearoff",
  role: "tearoff",
});

