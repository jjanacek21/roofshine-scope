export function findAssembly(roofType: string | null | undefined): CbAssembly | null {
  const raw = (roofType ?? "").trim().toLowerCase();
  if (!raw) return null;
  let best: CbAssembly | null = null;
  let bestLen = 0;
  for (const a of CB_ASSEMBLIES) {
    for (const alias of a.aliases) {
      if (raw.includes(alias) && alias.length > bestLen) {
        best = a;
        bestLen = alias.length;
      }
    }
  }
  return best;
}
